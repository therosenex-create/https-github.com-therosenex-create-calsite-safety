export function t(locale: Locale, key: string): string {
  if (key.startsWith("enum.")) {
    const pair = enums[key.slice(5)];
    if (!pair) return key;
    return locale === "es" ? pair[1] : pair[0];
  }
  const table = locale === "es" ? es : en;
  return table[key as Key] ?? en[key as Key] ?? key;
}

export function errorText(locale: Locale, code: string, field?: string): string {
  const message = t(locale, `errors.${code}`);
  if (message === `errors.${code}`) {
    return t(locale, "errors.generic");
  }
  if (!field || field === "form") return message;
  const label = t(locale, `fields.${field}`);
  const prefix = label.startsWith("fields.") ? field : label;
  return `${prefix}: ${message}`;
}
